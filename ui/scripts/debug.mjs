import { chromium } from 'playwright';
const BASE = process.env.BASE ?? 'http://localhost:8082';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1000, height: 800 } });
page.on('console', (m) => { if (m.text().includes('[dbg]')) console.log('>', m.text()); });
const run = Date.now().toString(36);
await page.goto(`${BASE}/setup`);
await page.getByText('Set up Curtain').waitFor({ timeout: 15000 });
await page.getByLabel('Email', { exact: true }).fill(`dbg5-${run}@example.com`);
await page.getByLabel('Password', { exact: true }).fill('sandi-rahasia-ui');
await page.getByLabel('Confirm password', { exact: true }).fill('sandi-rahasia-ui');
await page.locator('form button[type="submit"]').click();
await page.waitForURL('**/projects', { timeout: 120000 });
await page.getByRole('button', { name: 'New project' }).first().click();
await page.getByLabel('Project name').fill('dbg-project');
await page.getByRole('button', { name: 'Create project' }).click();
await page.getByRole('link', { name: 'Open project' }).first().click();
await page.waitForURL(/\/projects\/\d+$/);
await page.getByRole('button', { name: 'Environment', exact: true }).click();
await page.getByLabel('Environment name').fill('production');
await page.getByRole('button', { name: 'Create environment' }).click();
await page.waitForTimeout(600);
console.log('=== open #1 ===');
await page.getByRole('button', { name: 'New variable', exact: true }).click();
await page.getByLabel('Name', { exact: true }).fill('K1');
await page.getByLabel('Value', { exact: true }).fill('V1');
await page.getByRole('button', { name: 'Add variable' }).click();
await page.waitForTimeout(1200);
console.log('=== open #2 ===');
await page.getByRole('button', { name: 'New variable', exact: true }).click();
await page.waitForTimeout(800);
console.log('dialogs:', await page.locator('[role="dialog"]').count());
await browser.close();
