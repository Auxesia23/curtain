#!/usr/bin/env node
/**
 * Generate test vectors for internal/cli/testdata/vectors.json.
 *
 * These vectors use the same primitives as the browser/SvelteKit implementation
 * (WebCrypto + hash-wasm), so `go test ./internal/cli` verifies cross-language
 * compatibility rather than only testing a Go round trip.
 *
 * Regenerate the vectors if the cryptographic specification changes:
 *   cd ui && node scripts/cli-vectors.mjs
 *
 * Requires node_modules (hash-wasm). Run `npm install` first if needed.
 */
import { argon2id } from 'hash-wasm';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, '..', '..', 'internal', 'cli', 'testdata', 'vectors.json');

const PASSWORD = 'kata-sandi-vektor-curtain-2026';

const encoder = new TextEncoder();

const RSA_ALGORITHM = {
	name: 'RSA-OAEP',
	modulusLength: 2048,
	publicExponent: new Uint8Array([0x01, 0x00, 0x01]),
	hash: 'SHA-256'
};
const PRIVATE_KEY_AAD = encoder.encode('curtain.private-key.v1');
const VARIABLE_AAD = encoder.encode('curtain.variable.v1');

const b64 = (data) =>
	Buffer.from(data instanceof Uint8Array ? data : new Uint8Array(data)).toString('base64');
const unb64 = (text) => new Uint8Array(Buffer.from(text, 'base64'));
const randomBytes = (length) => crypto.getRandomValues(new Uint8Array(length));

function concat(...parts) {
	const total = parts.reduce((sum, part) => sum + part.length, 0);
	const out = new Uint8Array(total);
	let offset = 0;
	for (const part of parts) {
		out.set(part, offset);
		offset += part.length;
	}
	return out;
}

async function deriveMasterKey(password, kdf) {
	const result = await argon2id({
		password,
		salt: unb64(kdf.salt),
		parallelism: kdf.params.p,
		iterations: kdf.params.t,
		memorySize: kdf.params.m,
		hashLength: kdf.params.hash_length,
		outputType: 'binary'
	});
	return new Uint8Array(result);
}

async function hkdfBits(masterKey, info) {
	const ikm = await crypto.subtle.importKey('raw', masterKey, 'HKDF', false, ['deriveBits']);
	const bits = await crypto.subtle.deriveBits(
		{
			name: 'HKDF',
			hash: 'SHA-256',
			salt: encoder.encode('curtain.kdf.v1'),
			info: encoder.encode(info)
		},
		ikm,
		256
	);
	return new Uint8Array(bits);
}

async function encryptGCM(key, plaintext, aad) {
	const iv = randomBytes(12);
	const ciphertext = await crypto.subtle.encrypt(
		{ name: 'AES-GCM', iv, additionalData: aad },
		key,
		plaintext
	);
	return b64(concat(iv, new Uint8Array(ciphertext)));
}

async function main() {
	const kdf = {
		algorithm: 'argon2id',
		salt: b64(randomBytes(16)),
		params: { m: 65536, t: 3, p: 1, hash_length: 32 }
	};

	const masterKey = await deriveMasterKey(PASSWORD, kdf);
	const authKey = b64(await hkdfBits(masterKey, 'auth-key-v1'));
	const wrapKeyRaw = await hkdfBits(masterKey, 'private-key-wrap-v1');
	const wrapKey = await crypto.subtle.importKey('raw', wrapKeyRaw, { name: 'AES-GCM' }, false, [
		'encrypt'
	]);

	// Identity: RSA keypair and encrypted private key.
	const keypair = await crypto.subtle.generateKey(RSA_ALGORITHM, true, [
		'wrapKey',
		'unwrapKey',
		'encrypt',
		'decrypt'
	]);
	const publicKey = b64(await crypto.subtle.exportKey('spki', keypair.publicKey));
	const pkcs8 = await crypto.subtle.exportKey('pkcs8', keypair.privateKey);
	const encryptedPrivateKey = await encryptGCM(wrapKey, new Uint8Array(pkcs8), PRIVATE_KEY_AAD);

	// Project key + variable.
	const projectKeyRaw = randomBytes(32);
	const projectKey = await crypto.subtle.importKey('raw', projectKeyRaw, { name: 'AES-GCM' }, true, [
		'encrypt'
	]);
	const wrappedProjectKey = b64(
		await crypto.subtle.wrapKey('raw', projectKey, keypair.publicKey, { name: 'RSA-OAEP' })
	);

	const variables = [
		{ key: 'DATABASE_URL', value: `postgres://demo:${b64(randomBytes(6))}@db.internal:5432/app` },
		{ key: 'API_TOKEN', value: `tok_${b64(randomBytes(12))}` },
		{ key: 'EMPTY_VALUE', value: '' },
		{ key: 'UNICODE_NAME_😀', value: 'nilai dengan émoji & spasi' }
	];
	for (const v of variables) {
		v.encrypted_key = await encryptGCM(projectKey, encoder.encode(v.key), VARIABLE_AAD);
		v.encrypted_value = await encryptGCM(projectKey, encoder.encode(v.value), VARIABLE_AAD);
	}

	const fixture = {
		note: 'Generated by ui/scripts/cli-vectors.mjs. Do not edit manually.',
		password: PASSWORD,
		kdf,
		auth_key: authKey,
		wrap_key: b64(wrapKeyRaw),
		public_key: publicKey,
		private_key_pkcs8: b64(new Uint8Array(pkcs8)),
		encrypted_private_key: encryptedPrivateKey,
		project_key: b64(projectKeyRaw),
		wrapped_project_key: wrappedProjectKey,
		variables
	};

	mkdirSync(dirname(outPath), { recursive: true });
	writeFileSync(outPath, JSON.stringify(fixture, null, 2) + '\n');
	console.log(`vectors ditulis ke ${outPath}`);
}

main().catch((error) => {
	console.error(error);
	process.exit(1);
});
